package com.example.heimdall.bench.report;

import com.example.heimdall.bench.routing.RouterCatalog;
import com.example.heimdall.bench.routing.RoutingQualityAnalysis;
import com.example.heimdall.bench.routing.RoutingQualityAnalysis.Result;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Runs {@link RoutingQualityAnalysis} over every algorithm in the catalog and
 * emits the markdown tables that go into {@code BENCHMARKS.md}.
 *
 * <p>Deterministic by construction - fixed key set, no timing, no randomness -
 * so re-running it on any machine reproduces the same numbers exactly. That is
 * the whole point of separating it from the JMH throughput runs: these are
 * properties of the algorithms, not of the hardware.
 */
public final class RoutingQualityReport {

    private static final int KEY_COUNT = 200_000;
    private static final int[] CLUSTER_SIZES = {2, 3, 8, 32};

    public static void main(String[] args) throws IOException {
        StringBuilder out = new StringBuilder();
        out.append("<!-- generated by RoutingQualityReport; do not edit by hand -->\n\n");

        for (int members : CLUSTER_SIZES) {
            List<Result> results = new ArrayList<>();
            for (RouterCatalog.Variant variant : RouterCatalog.ALL) {
                results.add(RoutingQualityAnalysis.analyse(variant, members, KEY_COUNT));
            }
            appendClusterSection(out, members, results);
        }

        String markdown = out.toString();
        System.out.print(markdown);
        if (args.length > 0) {
            Files.writeString(Path.of(args[0]), markdown);
            System.err.println("wrote " + args[0]);
        }
    }

    private static void appendClusterSection(StringBuilder out, int members, List<Result> results) {
        out.append("### ").append(members).append(" primaries, ")
                .append(String.format(Locale.ROOT, "%,d", KEY_COUNT)).append(" keys\n\n");
        out.append("| algorithm | peak load | min load | CoV | churn on loss of `primary-0` | vs optimal | churn on join | vs optimal | routing state |\n");
        out.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|\n");

        for (Result r : results) {
            out.append("| `").append(r.variant().id()).append("` | ")
                    .append(fmt(r.balance().peakLoadFactor())).append("x | ")
                    .append(fmt(r.balance().minLoadFactor())).append("x | ")
                    .append(fmt(r.balance().coefficientOfVariation())).append(" | ")
                    .append(pct(r.removalChurn().movedFraction())).append(" | ")
                    .append(fmt(r.removalChurn().excessFactor())).append("x | ")
                    .append(pct(r.additionChurn().movedFraction())).append(" | ")
                    .append(fmt(r.additionChurn().excessFactor())).append("x | ")
                    .append(bytes(r.footprintBytes())).append(" |\n");
        }

        double optimalRemoval = 1.0 / members;
        double optimalAddition = 1.0 / (members + 1);
        out.append("\nTheoretical floor for churn at this size: **").append(pct(optimalRemoval))
                .append("** on loss, **").append(pct(optimalAddition)).append("** on join. ")
                .append("Peak load is the busiest member's share of the keyspace divided by its fair share; ")
                .append("1.00x is perfect, and it is the number that decides which node saturates first.\n\n");
    }

    private static String fmt(double value) {
        return String.format(Locale.ROOT, "%.3f", value);
    }

    private static String pct(double fraction) {
        return String.format(Locale.ROOT, "%.2f%%", fraction * 100);
    }

    private static String bytes(long value) {
        if (value < 1024) {
            return value + " B";
        }
        return String.format(Locale.ROOT, "%.1f KiB", value / 1024.0);
    }
}
